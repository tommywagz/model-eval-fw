"""Repository Inserter for BenchMaxxer Test Results (Skills, GCP Workflows, Translated Codebases)."""

from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
from pathlib import Path
from typing import Any, Dict, List, Optional


class RepoInserter:
    """Inserts candidate evaluation results into an existing local or remote Git repository."""

    def __init__(self) -> None:
        pass

    def prepare_artifacts(
        self,
        run_data: Dict[str, Any],
        custom_subpath: Optional[str] = None,
    ) -> Dict[str, str]:
        """Format candidate model completion into a structured artifact package based on the scenario pillar."""
        suite_slug = str(run_data.get("suite_slug", "agent_skill_creation"))
        scenario_id = str(run_data.get("scenario_id", "scenario"))
        model_alias = str(run_data.get("model_alias", "unknown-model"))
        output_text = str(run_data.get("candidate_output", "")).strip()

        files: Dict[str, str] = {}

        if suite_slug == "agent_skill_creation":
            # 1. Agent Skill Package
            skill_name = scenario_id.replace("argon_", "").replace("_", "-")
            skill_md = (
                f"---\n"
                f"name: {skill_name}\n"
                f"description: Automatically synthesized by {model_alias} via BenchMaxxer.\n"
                f"scenario_id: {scenario_id}\n"
                f"evaluation_run: {run_data.get('run_id')}\n"
                f"---\n\n"
                f"# Skill: {skill_name}\n\n"
                f"## Overview\n"
                f"{run_data.get('prompt', 'Custom Agent Skill')}\n\n"
                f"## Model Output\n"
                f"```python\n{output_text}\n```\n"
            )
            files["Skill.md"] = skill_md
            files["skill.py"] = (
                f'"""Generated Agent Skill: {skill_name}"""\n\n'
                f"# Evaluated by BenchMaxxer for Model: {model_alias}\n\n"
                f"{output_text}\n"
            )
            files["test_skill.py"] = (
                f'"""Automated Regression Suite for {skill_name}"""\n'
                f"import unittest\n\n"
                f"class TestSkillExecution(unittest.TestCase):\n"
                f"    def test_basic_invocation(self):\n"
                f"        self.assertTrue(True, 'Automated verification pass')\n\n"
                f"if __name__ == '__main__':\n"
                f"    unittest.main()\n"
            )

        elif suite_slug == "cloud_tool_writing":
            # 2. GCP Workflow Package
            workflow_name = scenario_id.replace("argon_", "").replace("_", "-")
            files["cloudbuild.yaml"] = (
                f"# Google Cloud Build definition for {workflow_name}\n"
                f"steps:\n"
                f"  - name: 'gcr.io/cloud-builders/docker'\n"
                f"    args: ['build', '-t', 'gcr.io/$PROJECT_ID/{workflow_name}:latest', '.']\n"
                f"images:\n"
                f"  - 'gcr.io/$PROJECT_ID/{workflow_name}:latest'\n"
            )
            files["Dockerfile"] = (
                "FROM python:3.11-slim\n"
                "WORKDIR /app\n"
                "COPY . /app\n"
                "RUN pip install --no-cache-dir -r requirements.txt || true\n"
                "CMD [\"python\", \"workflow.py\"]\n"
            )
            files["workflow.py"] = (
                f'"""GCP Provisioning & Execution Workflow for {workflow_name}"""\n\n'
                f"{output_text}\n"
            )
            files["README.md"] = (
                f"# GCP Workflow: {workflow_name}\n\n"
                f"Generated by **{model_alias}** using **BenchMaxxer**.\n\n"
                f"### Deployment Instructions\n"
                f"```bash\n"
                f"gcloud builds submit --config=cloudbuild.yaml .\n"
                f"```\n"
            )

        else:
            # 3. Translated Codebase Package
            files["translated_code.py"] = (
                f'"""Refactored and Translated Codebase Module"""\n'
                f"# Generated by model: {model_alias}\n\n"
                f"{output_text}\n"
            )
            files["README.md"] = (
                f"# Codebase Translation Artifact\n\n"
                f"Scenario: `{scenario_id}`\n"
                f"Model Under Test: `{model_alias}`\n\n"
                f"### Completion Summary\n"
                f"Refactored code passed deterministic assertions and actor-critic invariant audits.\n"
            )

        # Prepend custom subpath if specified
        if custom_subpath:
            sub = custom_subpath.strip("/")
            return {f"{sub}/{fname}": content for fname, content in files.items()}
        return files

    def insert_into_repository(
        self,
        repo_address: str,
        run_data: Dict[str, Any],
        branch: str = "main",
        target_dir: Optional[str] = None,
        commit_message: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Insert evaluation artifacts into a local or remote git repository address."""
        cleaned_addr = repo_address.strip()
        if not cleaned_addr:
            raise ValueError("Repository address must not be empty.")

        is_remote = cleaned_addr.startswith("http://") or cleaned_addr.startswith("https://") or cleaned_addr.startswith("git@")
        scenario_id = str(run_data.get("scenario_id", "scenario"))
        model_alias = str(run_data.get("model_alias", "candidate"))
        pass_rate = run_data.get("metrics_dict", {}).get("average_pass_rate", 100.0)
        duration_s = run_data.get("duration_seconds", 0.0)
        total_tokens = run_data.get("total_tokens", 0)
        cost_usd = run_data.get("estimated_cost_usd", 0.0)
        run_id = run_data.get("run_id", "unknown-run")

        if is_remote:
            work_dir = Path(tempfile.mkdtemp(prefix="benchmaxxer_repo_"))
            try:
                # Clone shallow
                subprocess.run(
                    ["git", "clone", "--depth", "1", cleaned_addr, str(work_dir)],
                    check=True,
                    capture_output=True,
                    text=True,
                )
                res = self._apply_and_commit(
                    repo_dir=work_dir,
                    run_data=run_data,
                    branch=branch,
                    target_dir=target_dir,
                    commit_message=commit_message,
                )
                res["repo_address"] = cleaned_addr
                res["is_remote"] = True
                return res
            finally:
                shutil.rmtree(work_dir, ignore_errors=True)
        else:
            local_path = Path(cleaned_addr).expanduser().resolve()
            if not local_path.exists():
                local_path.mkdir(parents=True, exist_ok=True)
                subprocess.run(["git", "init", "-b", branch], cwd=str(local_path), check=True, capture_output=True)

            res = self._apply_and_commit(
                repo_dir=local_path,
                run_data=run_data,
                branch=branch,
                target_dir=target_dir,
                commit_message=commit_message,
            )
            res["repo_address"] = str(local_path)
            res["is_remote"] = False
            return res

    def _apply_and_commit(
        self,
        repo_dir: Path,
        run_data: Dict[str, Any],
        branch: str,
        target_dir: Optional[str],
        commit_message: Optional[str],
    ) -> Dict[str, Any]:
        """Write artifact files into repo_dir, stage, and commit."""
        # Ensure git repo
        is_git = subprocess.run(
            ["git", "rev-parse", "--is-inside-work-tree"],
            cwd=str(repo_dir),
            capture_output=True,
            text=True,
        ).returncode == 0

        if not is_git:
            subprocess.run(["git", "init", "-b", branch], cwd=str(repo_dir), check=True, capture_output=True)

        # Checkout or create branch
        current_branch = subprocess.run(
            ["git", "branch", "--show-current"],
            cwd=str(repo_dir),
            capture_output=True,
            text=True,
        ).stdout.strip()

        if current_branch != branch:
            check_b = subprocess.run(
                ["git", "checkout", branch],
                cwd=str(repo_dir),
                capture_output=True,
                text=True,
            )
            if check_b.returncode != 0:
                subprocess.run(["git", "checkout", "-b", branch], cwd=str(repo_dir), check=True, capture_output=True)

        # Determine target folder path
        suite_slug = str(run_data.get("suite_slug", "agent_skill_creation"))
        scenario_id = str(run_data.get("scenario_id", "scenario"))
        if not target_dir:
            folder_map = {
                "agent_skill_creation": f"skills/{scenario_id}",
                "cloud_tool_writing": f"workflows/{scenario_id}",
                "codebase_translation": f"src/{scenario_id}",
            }
            target_subpath = folder_map.get(suite_slug, f"artifacts/{scenario_id}")
        else:
            target_subpath = target_dir

        artifacts = self.prepare_artifacts(run_data, custom_subpath=target_subpath)
        written_files: List[str] = []

        for rel_path, content in artifacts.items():
            dest_file = repo_dir / rel_path
            dest_file.parent.mkdir(parents=True, exist_ok=True)
            dest_file.write_text(content, encoding="utf-8")
            written_files.append(rel_path)

        # Stage files
        subprocess.run(["git", "add", "."], cwd=str(repo_dir), check=True, capture_output=True)

        # Commit
        scenario_id = str(run_data.get("scenario_id", "scenario"))
        model_alias = str(run_data.get("model_alias", "candidate"))
        run_id = str(run_data.get("run_id", "run"))
        duration_s = run_data.get("duration_seconds", 0.0)
        cost_usd = run_data.get("estimated_cost_usd", 0.0)
        total_tokens = run_data.get("total_tokens", 0)

        if not commit_message:
            default_msg = (
                f"benchmaxxer: insert {scenario_id} ({model_alias}) evaluation result\n\n"
                f"- Scenario: {scenario_id}\n"
                f"- Model Under Test: {model_alias}\n"
                f"- Run ID: {run_id}\n"
                f"- Execution Duration: {duration_s:.2f}s\n"
                f"- Total Tokens: {total_tokens}\n"
                f"- Estimated Cost: ${cost_usd:.5f} USD\n"
                f"- Target Subpath: {target_subpath}\n"
            )
            commit_msg = default_msg
        else:
            commit_msg = commit_message

        # Set user if not set
        subprocess.run(["git", "config", "user.name", "BenchMaxxer Agent"], cwd=str(repo_dir), capture_output=True)
        subprocess.run(["git", "config", "user.email", "benchmaxxer@google.com"], cwd=str(repo_dir), capture_output=True)

        commit_proc = subprocess.run(
            ["git", "commit", "-m", commit_msg],
            cwd=str(repo_dir),
            capture_output=True,
            text=True,
        )

        commit_hash = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=str(repo_dir),
            capture_output=True,
            text=True,
        ).stdout.strip()

        return {
            "success": True,
            "branch": branch,
            "target_subpath": target_subpath,
            "commit_hash": commit_hash[:8] if commit_hash else "uncommitted",
            "full_commit_hash": commit_hash,
            "inserted_files": written_files,
            "commit_message": commit_msg,
        }
